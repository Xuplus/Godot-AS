#!/usr/bin/env python
"""Generates the C++ for a project's AngelScript files (ahead-of-time compilation).

    python tools/aot.py --project demo --out build/aot/demo
    python -m SCons target=template_release aot=build/aot/demo

Then export with the AngelScript > Compiled Scripts option on (tools/export_demo.py --aot). The game
runs its script functions as native code; functions whose script changed since run in the VM.

The editor generates code for 64-bit platforms (Windows, Linux, macOS, Android). 32-bit platforms
(the web) need code generated by a 32-bit game build that includes the generator:

    python -m SCons arch=x86_32 target=template_debug aot_generator=yes
    python tools/export_demo.py --aot --debug --arch x86_32 "Windows Desktop"
    python tools/aot.py --exe build/windows-x86_32/godot_as_demo.console.exe --out build/aot/demo32
    python -m SCons platform=web threads=no target=template_release aot=build/aot/demo32

See docs/aot.md. Godot (an editor build) is found through the GODOT environment variable (default:
godot on PATH).
"""

import argparse
import json
import os
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

DRIVER = """extends SceneTree

func _initialize() -> void:
	var out: String = OS.get_cmdline_user_args()[0]
	var report: Dictionary = AngelScriptLanguage.generate_aot(out)
	print("AOT_REPORT ", JSON.stringify(report))
	quit(1 if report.has("error") else 0)
"""


def generate(godot, project, out_dir, verbose=False, exe=None):
    out_dir = os.path.abspath(out_dir)
    os.makedirs(out_dir, exist_ok=True)
    out_file = os.path.join(out_dir, "aot_scripts.gen.cpp").replace("\\", "/")
    with tempfile.TemporaryDirectory() as tmp:
        log = os.path.join(tmp, "aot.log")
        if exe:
            # An exported game (built with aot_generator=yes) generates from the bytecode it loaded.
            cmd = [os.path.abspath(exe), "--headless", "--log-file", log, "--", "--angelscript-aot=" + out_file]
        else:
            driver = os.path.join(tmp, "aot_driver.gd")
            with open(driver, "w", encoding="utf-8", newline="\n") as f:
                f.write(DRIVER)
            cmd = [godot, "--headless", "--path", os.path.abspath(project), "--log-file", log, "--script", driver, "--", out_file]
        r = subprocess.run(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        text = open(log, encoding="utf-8", errors="replace").read() if os.path.exists(log) else ""
    for line in text.splitlines():
        if line.startswith("AOT_REPORT "):
            report = json.loads(line[len("AOT_REPORT "):])
            slow = report.pop("calls_through_vm", {})
            print("Compiled %d functions: %d of %d instructions native, %d registered functions called directly." % (
                report.get("functions", 0), report.get("native_instructions", 0), report.get("instructions", 0), report.get("direct_calls", 0)))
            if slow and verbose:
                print("Registered functions still called through the VM (call sites):")
                for decl, count in sorted(slow.items(), key=lambda kv: -kv[1]):
                    print("  %4d  %s" % (count, decl))
            if "error" in report:
                print("Error: " + report["error"])
        elif "ERROR" in line:
            print(line)
    if r.returncode != 0:
        print("Generation failed (exit code %d)." % r.returncode)
    else:
        print("Wrote " + out_file)
    return r.returncode


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--project", default=os.path.join(ROOT, "demo"), help="Godot project folder")
    parser.add_argument("--out", default=os.path.join(ROOT, "build", "aot", "demo"), help="folder for the generated C++")
    parser.add_argument("--exe", help="generate with an exported game (for 32-bit platforms) instead of the editor")
    parser.add_argument("--verbose", action="store_true", help="list the registered functions still called through the VM")
    args = parser.parse_args()
    return generate(os.environ.get("GODOT", "godot"), args.project, args.out, args.verbose, args.exe)


if __name__ == "__main__":
    sys.exit(main())
